// One-off generator: Natural Earth 110m land → compact SVG path module.
// Run: node scripts/generateWorldOutline.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const W = 464;
const H = 232;

const geo = JSON.parse(readFileSync('/tmp/ne_110m_land.geojson', 'utf8'));

const project = ([lng, lat]) => [
  Math.round(((lng + 180) / 360) * W * 10) / 10,
  Math.round(((90 - lat) / 180) * H * 10) / 10,
];

const segments = [];

const ringsFrom = (geometry) =>
  geometry.type === 'Polygon'
    ? geometry.coordinates
    : geometry.type === 'MultiPolygon'
      ? geometry.coordinates.flat()
      : [];

for (const feature of geo.features) {
  for (const ring of ringsFrom(feature.geometry)) {
    // Decimate: keep ~40 points per ring, always including both ends.
    const step = Math.max(1, Math.floor(ring.length / 40));
    const projected = [];
    for (let i = 0; i < ring.length; i += 1) {
      if (i % step === 0 || i === ring.length - 1) {
        projected.push(project(ring[i]));
      }
    }
    const [start, ...rest] = projected;
    const commands = [`M ${start[0]} ${start[1]}`];
    let last = start;
    for (const point of rest) {
      if (point[0] === last[0] && point[1] === last[1]) continue;
      commands.push(`L ${point[0]} ${point[1]}`);
      last = point;
    }
    if (commands.length > 1) segments.push(`${commands.join(' ')} Z`);
  }
}

const path = segments.join(' ');
const out = `// Generated by scripts/generateWorldOutline.mjs — do not edit by hand.
// Source: Natural Earth 110m land (public domain), decimated and projected
// onto the equirectangular frame used by StationMiniMap.
export const WORLD_MAP_WIDTH = ${W};
export const WORLD_MAP_HEIGHT = ${H};

export function projectToWorld(lat: number, lng: number): { x: number; y: number } {
  return {
    x: ((lng + 180) / 360) * WORLD_MAP_WIDTH,
    y: ((90 - lat) / 180) * WORLD_MAP_HEIGHT,
  };
}

export const WORLD_LAND_PATH = ${JSON.stringify(path)};
`;

writeFileSync('src/lib/worldOutline.ts', out);
console.log('rings:', segments.length, 'bytes:', out.length);
